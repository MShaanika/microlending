    /** Finds a live (not merged-away) split leg by split_no, flashing+redirecting on failure -- same pattern as loadOr404(). */
    private function findLiveSplitOr404(int $debitOrderId, int $splitNo, string $redirectTo): ?array
    {
        foreach ($this->splitLegs->activeForDebitOrder($debitOrderId) as $s) {
            if ((int) $s['split_no'] === $splitNo) {
                return $s;
            }
        }
        Session::flash('error', 'Split #' . $splitNo . ' not found.');
        $this->redirect($redirectTo);
        return null;
    }

    private function loadOr404(string $id): ?array
    {
        $debitOrder = $this->debitOrders->find((int) $id);
        if (!$debitOrder) {
            Session::flash('error', 'Debit order not found.');
            $this->redirect('/debit-orders');
            return null;
        }
        return $debitOrder;
    }

    private function verifyCsrfOrRedirect(string $id, ?string $redirectTo = null): bool
    {
        if (!Security::verifyCsrf($_POST['_csrf'] ?? null)) {
            Session::flash('error', 'Security token expired. Please try again.');
            $this->redirect($redirectTo ?? '/debit-orders/' . $id);
            return false;
        }
        return true;
    }

    /**
     * Collexia's frontEndUserName -- "the user on your system requesting"
     * an action (spec 9.4/9.10/9.16, Required; 9.2 Message Info,
     * Conditional). Per the spec this should be the actual DesertLedger
     * user who triggered the request, but Collexia has so far only
     * provisioned a single value ("willemk", Configuration sheet, Desert
     * Ledger Test Pack V4.0) -- not yet one per staff member -- so that
     * configured value is used for every mandate action until individual
     * employees get their own. Falls back to the logged-in staff member's
     * own username if the setting is ever blank (every action method here
     * runs behind Auth::authorize() first, so a logged-in user is always
     * present).
     */
    private function frontEndUserName(): string
    {
        $configured = $this->settings->frontEndUsername();
        return $configured !== '' ? $configured : (string) (Auth::user()['username'] ?? '');
    }

    /**
     * V4 mandate load additions (Desert Ledger Test Pack V4.0, Configuration
     * sheet: "Include dateOfBirth, gender, debtorTelephone where
     * applicable") -- each one is genuinely optional data on a borrower
     * (date_of_birth/gender can be blank on an older record), so each is
     * only included when actually on file rather than sending a guessed or
     * empty value. gender is a numeric code per Collexia (1=Male, 2=Female,
     * confirmed directly, not from the spec); 'Other' has no agreed code so
     * is left out like a blank gender would be.
     */
    private static function mandateDebtorExtraFields(array $debitOrder): array
    {
        $fields = [];
        if (!empty($debitOrder['date_of_birth'])) {
            $fields['dateOfBirth'] = date('Ymd', strtotime((string) $debitOrder['date_of_birth']));
        }
        $genderCode = ['Male' => 1, 'Female' => 2][$debitOrder['gender'] ?? ''] ?? null;
        if ($genderCode !== null) {
            $fields['gender'] = $genderCode;
        }
        if (!empty($debitOrder['phone'])) {
            $fields['debtorTelephone'] = $debitOrder['phone'];
        }
        return $fields;
    }

    /**
     * NOT CONFIRMED against Collexia's actual expected encoding -- see
     * class docblock. 4 chars merchant GID in hex, 4 chars date, 6 chars
     * zero-padded debit order id, for exactly 14 characters and guaranteed
     * local uniqueness (but not necessarily the format Collexia expects).
     *
     * $splitNo (1-10) is for a split order's Nth mandate, which needs its
     * own distinct reference from the same debit order id -- shortens the
     * zero-padded id segment from 6 to 5 digits to make room for a
     * 1-character split suffix (splitSuffix()) while staying within the
     * 14-character total. Omitting $splitNo (the non-split case) is
     * byte-for-byte the original 6-digit encoding.
     */
    private function buildContractReference(int $debitOrderId, ?int $splitNo = null): string
    {
        $merchantGid = (int) $this->settings->get('collexia_merchant_gid');
        $gidHex = strtoupper(str_pad(dechex($merchantGid), 4, '0', STR_PAD_LEFT));
        $gidHex = substr($gidHex, -4);
        $dateSeg = date('md');
        $tellerSeg = $splitNo !== null
            ? str_pad((string) $debitOrderId, 5, '0', STR_PAD_LEFT) . self::splitSuffix($splitNo)
            : str_pad((string) $debitOrderId, 6, '0', STR_PAD_LEFT);
        return $gidHex . $dateSeg . $tellerSeg;
    }

    /**
     * Single-character encoding of a split number (1-10) for the 14-char
     * contractReference and the 10-char userReference (clientNo is no
     * longer suffixed -- see attemptSplitPlacement()). A letter, not a
     * digit (2026-10-16, was '1'-'9'/'X'): back when userReference was
     * loan-reference-based, this app's loan references were purely
     * numeric ("SDLOAN%04d"), so a digit suffix could read as a real,
     * different loan's reference -- see the 2026-10-17 docblock update on
     * attemptSplitPlacement() for why userReference is no longer
     * loan-reference-based at all. Kept as a letter regardless, since it's
     * still never mistaken for a continuation of the id-based value it now
     * suffixes.
     */
    private static function splitSuffix(int $splitNo): string
    {
        // A-Z (26 legs): a debit order registered as one mandate per
        // scheduled installment needs one leg per remaining installment,
        // which can exceed the old 10-leg ceiling.
        return chr(ord('A') + min(max($splitNo, 1), 26) - 1);
    }

    /**
     * The drill-down/history screen for a split debit order -- every split
     * transaction ever created for it, including ones folded away by a
     * merge, with which loan_schedules row's collection date (if any) each
     * corresponds to, and which currently-live splits are eligible to be
     * selected for a merge.
     */
    public function splitTransactions(string $id): void
    {
        Auth::authorize('collections.debit_orders');
        $debitOrder = $this->loadOr404($id);
        if (!$debitOrder) {
            return;
        }
        if (empty($debitOrder['split_enabled'])) {
            Session::flash('error', 'This debit order was not registered as a split.');
            $this->redirect('/debit-orders/' . $id);
            return;
        }

        $splits = $this->splitLegs->forDebitOrder((int) $id);

        $collectedBySplitNo = [];
        foreach ($this->collections->forDebitOrder((int) $id) as $c) {
            if ($c['payment_id'] && $c['split_no'] !== null) {
                $collectedBySplitNo[(int) $c['split_no']] = $c['payment_date'];
            }
        }

        // Rows that resulted FROM a merge: map the merged-into id back to
        // the split_no(s) that were folded into it, for the "Merged (from
        // #.. #..)" label.
        $mergeSources = [];
        $idToSplitNo = [];
        foreach ($splits as $s) {
            $idToSplitNo[(int) $s['id']] = (int) $s['split_no'];
            if ($s['merged_into_id']) {
                $mergeSources[(int) $s['merged_into_id']][] = (int) $s['split_no'];
            }
        }

        // split_no is a GLOBAL sequence across every installment this
        // debit order has ever split (so a later month's legs continue
        // from wherever an earlier month's left off), but total_splits is
        // scoped to just that one installment's own set (see
        // DebitOrderSplitLeg::liveForSchedule()) -- so "#<split_no> of
        // <total_splits>" alone can read as nonsense (e.g. "#3 of 2") once
        // a second month exists. This gives each leg its position WITHIN
        // its own installment's group instead, for an honest "#1 of 2" /
        // "#2 of 2" per month.
        $positionInInstallment = [];
        $seenPerSchedule = [];
        foreach ($splits as $s) {
            if ($s['merged_into_id']) {
                continue;
            }
            $key = $s['schedule_id'] ?? 'none';
            $seenPerSchedule[$key] = ($seenPerSchedule[$key] ?? 0) + 1;
            $positionInInstallment[(int) $s['id']] = $seenPerSchedule[$key];
        }

        $this->view('debit_orders/split_transactions', [
            'title' => 'Split Transactions - ' . $debitOrder['debit_order_no'],
            'debitOrder' => $debitOrder,
            'splits' => $splits,
            'collectedBySplitNo' => $collectedBySplitNo,
            'mergeSources' => $mergeSources,
            'idToSplitNo' => $idToSplitNo,
            'positionInInstallment' => $positionInInstallment,
            'mergeableIds' => $this->mergeableSplitIds((int) $id, $splits),
        ]);
    }

    /**
     * A split is mergeable only while it's still live (never itself
     * already merged away) AND has never actually collected a payment --
     * undoing a real collection isn't something a merge should attempt,
     * that needs an actual refund process. Not-yet-sent, rejected, pending,
     * and registered-but-not-yet-collected splits are all fair game; only
     * Cancelled (nothing left to merge) and already-collected splits are
     * excluded.
     */
    private function mergeableSplitIds(int $debitOrderId, array $splits): array
    {
        $ids = [];
        foreach ($splits as $s) {
            if ($s['merged_into_id'] !== null) {
                continue;
            }
            if (!in_array($s['collexia_api_status'], array_merge(self::SPLIT_UNSENT_STATUSES, self::SPLIT_LIVE_STATUSES), true)) {
                continue;
            }
            if ($this->splitLegs->hasPostedCollection($debitOrderId, (int) $s['split_no'])) {
                continue;
            }
            $ids[] = (int) $s['id'];
        }
        return $ids;
    }

    /**
     * Combines two or more selected split transactions into one. Any
     * selected split that's actually live at Collexia (Load Pending /
     * Registered) is cancelled there FIRST via the existing cancelMandate
     * call -- if any of those cancels fails, the whole merge is aborted
     * with no local changes at all, so a merge is never half-applied
     * against Collexia. Splits that were never sent (Not Placed / Load
     * Failed) need no API call. The selected rows are then marked
     * Cancelled and linked via merged_into_id to a single new split row
     * (status Not Placed) for the combined amount -- that new row is NOT
     * automatically placed; use the existing Place Mandate action for it
     * afterward, same as any other unplaced split.
     */
    public function mergeSplits(string $id): void
    {
        Auth::authorize('collections.debit_orders');
        $debitOrder = $this->loadOr404($id);
        if (!$debitOrder) {
            return;
        }
        if (!$this->verifyCsrfOrRedirect($id, '/debit-orders/' . $id . '/split-transactions')) {
            return;
        }

        $ids = array_values(array_unique(array_filter(array_map('intval', $_POST['split_ids'] ?? []))));
        if (count($ids) < 2) {
            Session::flash('error', 'Select at least two split transactions to merge.');
            $this->redirect('/debit-orders/' . $id . '/split-transactions');
            return;
        }

        $selected = $this->splitLegs->findManyForDebitOrder((int) $id, $ids);
        if (count($selected) !== count($ids)) {
            Session::flash('error', 'One or more selected transactions could not be found on this debit order.');
            $this->redirect('/debit-orders/' . $id . '/split-transactions');
            return;
        }

        $mergeable = $this->mergeableSplitIds((int) $id, $selected);
        foreach ($selected as $s) {
            if (!in_array((int) $s['id'], $mergeable, true)) {
                Session::flash('error', 'Split #' . $s['split_no'] . ' can no longer be merged (already merged, cancelled, or already collected a payment).');
                $this->redirect('/debit-orders/' . $id . '/split-transactions');
                return;
            }
        }

        // Checked BEFORE anything is cancelled at Collexia -- discovering
        // this only after the merge (debit order #36: splits #1 and #2
        // genuinely cancelled at Collexia, then the combined #4 rejected
        // with "10569 Mandate amount limit exceeded") leaves the amount
        // with no live mandate at all until someone notices and fixes it.
        $maxAmount = $this->settings->maxSingleMandateAmount();
        $combinedAmountCheck = round((float) array_sum(array_column($selected, 'leg_amount')), 2);
        if ($maxAmount !== null && $combinedAmountCheck > $maxAmount) {
            Session::flash('error', 'Merging these would total ' . format_money($combinedAmountCheck) . ', which exceeds the configured max single mandate amount of '
                . format_money($maxAmount) . '. Nothing was cancelled at Collexia -- choose a smaller combination.');
            $this->redirect('/debit-orders/' . $id . '/split-transactions');
            return;
        }

        $toCancelAtCollexia = array_values(array_filter(
            $selected,
            fn ($s) => in_array($s['collexia_api_status'], self::SPLIT_LIVE_STATUSES, true) && $s['collexia_api_contract_reference']
        ));

        $cancelResponses = [];
        if (!empty($toCancelAtCollexia)) {
            try {
                $client = new CollexiaEndoApiClient();
                foreach ($toCancelAtCollexia as $s) {
                    $cancelResponses[$s['id']] = $client->cancelMandate((string) $s['collexia_api_contract_reference'], $this->frontEndUserName());
                }
            } catch (\RuntimeException $e) {
                Session::flash('error', 'Could not cancel one of the selected transactions at Collexia, so the merge was not applied: ' . $e->getMessage());
                $this->redirect('/debit-orders/' . $id . '/split-transactions');
                return;
            }
        }

        $combinedAmount = round((float) array_sum(array_column($selected, 'leg_amount')), 2);
        $totalSplits = (int) $selected[0]['total_splits'];
        $newSplitNo = $this->splitLegs->nextSplitNo((int) $id);
        $newId = $this->splitLegs->upsert((int) $id, $newSplitNo, $combinedAmount, $totalSplits);

        $refs = [];
        foreach ($selected as $s) {
            $this->splitLegs->updateById((int) $s['id'], [
                'collexia_api_status' => 'Cancelled',
                'merged_into_id' => $newId,
                'collexia_api_synced_at' => date('Y-m-d H:i:s'),
                'collexia_api_last_response' => isset($cancelResponses[$s['id']]) ? json_encode($cancelResponses[$s['id']]) : $s['collexia_api_last_response'],
            ]);
            $refs[] = 'split #' . $s['split_no'] . ' (' . format_money($s['leg_amount'])
                . ($s['collexia_api_contract_reference'] ? ', was ' . $s['collexia_api_contract_reference'] . ' ' . $s['collexia_api_status'] : ', ' . $s['collexia_api_status'])
                . ')';
        }

        Audit::log(
            'Update',
            'Debit Orders',
            'Merged ' . count($selected) . ' split transaction(s) on debit order #' . $id . ' (' . $debitOrder['debit_order_no'] . ') into new split #' . $newSplitNo
                . ' totalling ' . format_money($combinedAmount) . '. Merged: ' . implode('; ', $refs)
        );

        Session::flash('success', count($selected) . ' split transaction(s) merged into one ' . format_money($combinedAmount) . ' transaction (split #' . $newSplitNo . '). Place its mandate when ready.');
        $this->redirect('/debit-orders/' . $id . '/split-transactions');
    }

    /**
     * Recovers from a merge that turned out to combine too much (e.g.
     * rejected with "10569 Mandate amount limit exceeded") -- only usable
     * on a merged split that Load Failed, since its sources were already
     * genuinely cancelled at Collexia by the merge itself (see
     * mergeSplits()) and never re-registered; nothing further needs
     * cancelling here. Un-merging never resurrects the failed combined
     * split -- it retires it and creates fresh, brand-new split legs (Not
     * Placed) at the sources' original amounts, ready to be placed
     * independently via the normal Place/Retry flow.
     */
    public function unmergeSplit(string $id, string $splitNo): void
    {
        Auth::authorize('collections.debit_orders');
        $debitOrder = $this->loadOr404($id);
        if (!$debitOrder) {
            return;
        }
        $redirectTo = '/debit-orders/' . $id . '/split-transactions';
        if (!$this->verifyCsrfOrRedirect($id, $redirectTo)) {
            return;
        }

        $splitNo = (int) $splitNo;
        $target = null;
        foreach ($this->splitLegs->forDebitOrder((int) $id) as $s) {
            if ((int) $s['split_no'] === $splitNo) {
                $target = $s;
                break;
            }
        }

        if (!$target || $target['collexia_api_status'] !== 'Load Failed') {
            Session::flash('error', 'Only a Load Failed merged split can be un-merged.');
            $this->redirect($redirectTo);
            return;
        }

        $sources = $this->splitLegs->mergeSourcesFor((int) $target['id']);
        if (empty($sources)) {
            Session::flash('error', 'Split #' . $splitNo . ' did not result from a merge -- nothing to un-merge.');
            $this->redirect($redirectTo);
            return;
        }

        $created = [];
        foreach ($sources as $source) {
            $newSplitNo = $this->splitLegs->nextSplitNo((int) $id);
            $this->splitLegs->upsert((int) $id, $newSplitNo, (float) $source['leg_amount'], (int) $source['total_splits']);
            $created[] = 'split #' . $newSplitNo . ' (' . format_money($source['leg_amount']) . ', originally split #' . $source['split_no'] . ')';
        }

        $this->splitLegs->updateById((int) $target['id'], [
            'collexia_api_status' => 'Cancelled',
            'collexia_api_last_response' => 'Un-merged back into: ' . implode(', ', $created) . '. This combined amount is retired, never placed.',
            'collexia_api_synced_at' => date('Y-m-d H:i:s'),
        ]);

        Audit::log(
            'Update',
            'Debit Orders',
            'Un-merged failed split #' . $splitNo . ' (' . format_money($target['leg_amount']) . ') on debit order #' . $id . ' (' . $debitOrder['debit_order_no'] . ') back into: ' . implode('; ', $created)
        );

        Session::flash('success', 'Split #' . $splitNo . ' un-merged into ' . count($created) . ' fresh split(s): ' . implode(', ', $created) . '. Place their mandates when ready.');
        $this->redirect($redirectTo);
    }
}
