/**
 * Wires CollexiaEndoApiClient's mandate lifecycle (place/confirm/status/
 * cancel/reschedule) into the existing debit order screens, as additive
 * actions on /debit-orders/{id} -- entirely separate from that same
 * screen's existing Excel-batch registration, which is unaffected and
 * keeps working regardless of whether this integration is enabled.
 *
 * clientNo carries the staff-recognised DesertLedger loan reference (e.g.
 * "SDLOAN0003") -- the same value for every split leg of the same loan, so
 * Collexia's own portal never makes one loan look like two. userReference
 * only needs to be unique per concurrently-live mandate, so it's minted
 * from the debit order's own id instead (see placeSingleMandate() and
 * attemptSplitPlacement()) -- 2026-10-17, was the other way round until a
 * Collexia portal screenshot showed Client No, not User Reference,
 * displaying the loan reference everyone actually reads.
 *
 * contractReference for a SINGLE mandate is generated by CollexiaClient,
 * confirmed against Collexia's own Postman pre-request script (see that
 * class's docblock). The legacy buildContractReference()
 * below is kept ONLY for split mandates: the script's contractReference is
 * time-based (gid+MMDD+HHmmss) with no per-order component, so several
 * splits placed in the same second in placeSplitMandate()'s loop would
 * collide -- an open conflict flagged for Collexia rather than silently
 * worked around; see the implementation report.
 *
 * Split debit orders (debit_orders.split_enabled): the installment is
 * divided into 1-10 independent split transactions (DebitOrderSplitLeg,
 * amounts entered individually at registration, not necessarily equal),
 * each its own Collexia mandate. Place/Check Final Fate/Sync/Cancel
 * Mandate act on whichever splits are actually in the relevant state
 * (placement can happen incrementally -- e.g. only a newly-merged split
 * still needs placing while the others are already Registered), and roll
 * their combined state back onto debit_orders.collexia_api_status purely
 * for the existing single-badge summary. splitTransactions()/mergeSplits()
 * are the drill-down/merge screen -- see their docblocks. Reschedule
 * Installment and single-installment Cancel stay unsupported for split
 * orders (multiple mandates to pick from; use merge/cancel-mandate
 * instead).
 */
class DebitOrderCollexiaController extends Controller
{
    private DebitOrder $debitOrders;
    private DebitOrderSplitLeg $splitLegs;
    private DebitOrderInstallmentTarget $installmentTargets;
    private DebitOrderCollection $collections;
    private CollexiaSetting $settings;
    private Loan $loans;

    /** Statuses a split can still be pushed to Collexia from, or merged away from without needing an API cancel first. */
    private const SPLIT_UNSENT_STATUSES = ['Not Placed', 'Load Failed'];
    /** Statuses meaning Collexia actually has this mandate live -- must be cancelled there before it can be merged away. */
    private const SPLIT_LIVE_STATUSES = ['Load Pending', 'Registered'];

    public function __construct()
    {
        $this->debitOrders = new DebitOrder();
        $this->splitLegs = new DebitOrderSplitLeg();
        $this->installmentTargets = new DebitOrderInstallmentTarget();
        $this->collections = new DebitOrderCollection();
        $this->settings = new CollexiaSetting();
        $this->loans = new Loan();
    }

    /**
     * Flashes the last Collexia API call's exact request/response (no
     * credentials, see CollexiaClient::lastDebug()) so the next page load
     * can print it to the browser console -- UAT testing aid, not a
     * permanent audit trail (that's Audit::log(), unaffected by this).
     */
    private function flashCollexiaDebug(CollexiaEndoApiClient $client, string $action): void
    {
        $debug = $client->lastDebug();
        if ($debug === null) {
            return;
        }
        Session::flash('collexia_debug', json_encode(array_merge(['action' => $action], $debug)));
    }

    public function placeMandate(string $id): void
    {
        Auth::authorize('collections.debit_orders');
        $debitOrder = $this->loadOr404($id);
        if (!$debitOrder) {
            return;
        }
        if (!$this->verifyCsrfOrRedirect($id)) {
            return;
        }

        $banId = $this->resolveBanIdOrFlash($debitOrder, '/debit-orders/' . $id);
        if (!$banId) {
            return;
        }

        if ((int) ($debitOrder['split_enabled'] ?? 0) === 1) {
            $this->placeSplitMandate($debitOrder, $banId);
        } else {
            $this->placeSingleMandate($debitOrder, $banId);
        }

        $this->redirect('/debit-orders/' . $id);
    }

    /**
     * Retries placement for ONE specific still-failing/never-placed split
     * leg -- the targeted counterpart to placeMandate()'s "retry everything
     * eligible at once" behaviour. Useful exactly when some splits already
     * registered fine and only one (e.g. rejected with a Collexia-side
     * "Duplicate" error) needs another attempt, without re-touching the
     * ones that are already fine.
     */
    public function placeSingleSplitMandate(string $id, string $splitNo): void
    {
        Auth::authorize('collections.debit_orders');
        $debitOrder = $this->loadOr404($id);
        if (!$debitOrder) {
            return;
        }
        if (!$this->verifyCsrfOrRedirect($id, '/debit-orders/' . $id . '/split-transactions')) {
            return;
        }

        $redirectTo = '/debit-orders/' . $id . '/split-transactions';

        if ((int) ($debitOrder['split_enabled'] ?? 0) !== 1) {
            Session::flash('error', 'This debit order does not use split transactions.');
            $this->redirect($redirectTo);
            return;
        }

        $banId = $this->resolveBanIdOrFlash($debitOrder, $redirectTo);
        if (!$banId) {
            return;
        }

        $splitNo = (int) $splitNo;
        $split = null;
        foreach ($this->splitLegs->activeForDebitOrder((int) $id) as $s) {
            if ((int) $s['split_no'] === $splitNo) {
                $split = $s;
                break;
            }
        }

        if (!$split || !in_array($split['collexia_api_status'], self::SPLIT_UNSENT_STATUSES, true)) {
            Session::flash('error', 'Split #' . $splitNo . ' is not waiting to be placed.');
            $this->redirect($redirectTo);
            return;
        }

        if (!$this->installmentTargets->hasSnapshot((int) $id)) {
            $this->installmentTargets->snapshot((int) $id, $this->debitOrders->orderedUnpaidScheduleIds((int) $debitOrder['loan_id']));
        }

        $clientNoBase = $debitOrder['borrower_loan_ref_no'] ?: $debitOrder['debit_order_no'];

        $result = $this->attemptSplitPlacement($debitOrder, $split, $banId, $clientNoBase);
        $this->rollupSplitStatus((int) $id);

        Audit::log('Update', 'Debit Orders', 'Retried Collexia split mandate placement for debit order #' . $id . ' split #' . $splitNo . ' -> ' . ($result['success'] ? 'submitted' : 'rejected'));
        Session::flash($result['success'] ? 'success' : 'error', $result['message']);
        $this->redirect($redirectTo);
    }

    /** Flashes and returns null on failure -- callers just check for null and return. */
    private function resolveBanIdOrFlash(array $debitOrder, string $redirectTo): ?int
    {
        $banId = $debitOrder['bank_code'] ? CollexiaV3Codes::fromLegacyBankCode($debitOrder['bank_code']) : null;
        if (!$banId) {
            Session::flash('error', 'This debit order\'s bank has no known Collexia bank ID -- cannot place the mandate. Confirm the correct bank and re-save the debit order first.');
            $this->redirect($redirectTo);
            return null;
        }

        // Defensive, not expected to ever fire in normal use -- the debit
        // order form's own account_type dropdown (CollexiaCodes::ACCOUNT_TYPES)
        // only ever offers 1 or 2, matching Collexia's ValidValues exactly.
        // Guards against stale/legacy rows rather than silently sending an
        // unconfirmed value if one ever existed.
        if (!isset(CollexiaV3Codes::ACCOUNT_TYPES[(int) $debitOrder['account_type']])) {
            Session::flash('error', 'This debit order\'s account type is not a value Collexia recognises -- cannot place the mandate. Confirm the correct account type and re-save the debit order first.');
            $this->redirect($redirectTo);
            return null;
        }

        return $banId;
    }

    private function placeSingleMandate(array $debitOrder, int $banId): void
    {
        $id = (int) $debitOrder['id'];

        $maxAmount = $this->settings->maxSingleMandateAmount();
        $amount = (float) $debitOrder['debit_amount'];
        if ($maxAmount !== null && $amount > $maxAmount) {
            // See attemptSplitPlacement()'s identical guard -- rejected
            // locally, before calling Collexia, using direct evidence of
            // their "10569 Mandate amount limit exceeded" rejection.
            $message = 'This debit order\'s amount (' . format_money($amount) . ') exceeds the configured max single mandate amount of '
                . format_money($maxAmount) . ' -- not sent to Collexia. Use a split debit order instead.';
            $this->debitOrders->updateCollexiaApiState($id, [
                'collexia_api_status' => 'Load Failed',
                'collexia_api_last_response' => $message,
                'collexia_api_synced_at' => date('Y-m-d H:i:s'),
            ]);
            Session::flash('error', $message);
            return;
        }

        $collexiaClient = new CollexiaClient();
        $contractReference = $collexiaClient->buildContractReference();
        $noOfInstallments = max(1, $this->debitOrders->remainingInstallments((int) $debitOrder['loan_id']));
        // clientNo (spec 9.3: "Alphanumeric number for your client") now
        // carries the staff-recognised DesertLedger loan reference (e.g.
        // "SDLOAN0003"), per explicit instruction -- 2026-10-17, this used
        // to be borrower_no with the loan reference sent as userReference
        // instead, but a Collexia portal screenshot showed Client No (not
        // User Reference) is the column everyone actually reads as "which
        // loan is this". Falls back to debit_order_no only for a loan that
        // somehow has no loan_ref_no on file.
        $clientNoBase = $debitOrder['borrower_loan_ref_no'] ?: $debitOrder['debit_order_no'];
        $clientNo = substr((string) $clientNoBase, 0, 15);
        // userReference (spec 9.3: "Alphanumeric reference for the
        // mandate") only needs to be unique per concurrently-live mandate
        // -- it can no longer hold the loan reference now that clientNo
        // does, so it's minted from this debit order's own auto-increment
        // id instead: guaranteed unique, and never reads as a real loan
        // reference on Collexia's own records. contractReference stays
        // Collexia's own separately-generated 14-char match key and must
        // never be conflated with this.
        $userReference = 'DO' . str_pad((string) $id, 8, '0', STR_PAD_LEFT);

        // Recorded before the API call is even made (not only on success)
        // so the attempted contractReference/userReference are always on
        // file for traceability, even if Collexia rejects the request.
        $this->debitOrders->updateCollexiaApiState($id, [
            'collexia_api_contract_reference' => $contractReference,
            'collexia_client_no' => $clientNo,
            'collexia_user_reference' => $userReference,
        ]);

        $mandate = [
            'clientNo' => $clientNo,
            'userReference' => $userReference,
            'frequencyCode' => 4, // Monthly -- this app's debit orders are always monthly (debit_day is a day-of-month)
            'installmentAmount' => (float) $debitOrder['debit_amount'],
            'noOfInstallments' => $noOfInstallments,
            // Always the Remote GID, never 0 -- confirmed by Collexia.
            'origin' => (int) $this->settings->get('collexia_remote_gid'),
            'contractReference' => $contractReference,
            'magId' => CollexiaV3Codes::MAG_ID_ENDO,
            'initialAmount' => 0,
            'firstCollectionDate' => date('Ymd', strtotime((string) $debitOrder['start_date'])),
            'collectionDay' => CollexiaV3Codes::collectionDay((int) $debitOrder['debit_day']),
            'numberOfTrackingDays' => (int) $debitOrder['no_of_days_tracking'],
            'debtorAccountName' => $debitOrder['account_name'] ?: $debitOrder['borrower_name'],
            'debtorIdentificationType' => 1,
            'debtorIdentificationNo' => $debitOrder['id_number'],
            'debtorAccountNumber' => $debitOrder['account_number'],
            'debtorAccountType' => (int) $debitOrder['account_type'],
            'debtorBanId' => $banId,
        ] + ($this->settings->v4FieldsEnabled() ? self::mandateDebtorExtraFields($debitOrder) : []);

        try {
            $client = new CollexiaEndoApiClient();
            $client->loadMandate($mandate, $this->frontEndUserName());
            $this->flashCollexiaDebug($client, 'Mandate Load');

            $this->debitOrders->updateCollexiaApiState($id, [
                'collexia_api_status' => 'Load Pending',
                'collexia_api_last_response' => 'Mandate submitted. Call "Check Final Fate" to confirm registration.',
                'collexia_api_synced_at' => date('Y-m-d H:i:s'),
            ]);

            Audit::log('Update', 'Debit Orders', 'Placed Collexia API mandate for debit order #' . $id . ' (' . $contractReference . ', loan ref ' . $clientNo . ')');
            Session::flash('success', 'Mandate submitted (' . $contractReference . ', loan ref ' . $clientNo . '). Use "Check Final Fate" to confirm it registered.');
        } catch (CollexiaApiException $e) {
            if (isset($client)) {
                $this->flashCollexiaDebug($client, 'Mandate Load');
            }
            $this->debitOrders->updateCollexiaApiState($id, [
                'collexia_api_status' => 'Load Failed',
                'collexia_api_last_response' => $e->getMessage(),
                'collexia_api_synced_at' => date('Y-m-d H:i:s'),
            ]);
            Session::flash('error', 'The mandate was rejected: ' . $e->getMessage());
        } catch (\RuntimeException $e) {
            // A network-level failure (e.g. a timeout) does NOT mean
            // Collexia never received the request -- it may have been
            // accepted on their end with the response lost in transit. Mark
            // this visibly as Uncertain rather than leaving the previous
            // status untouched (which would be indistinguishable from
            // "never attempted" and could tempt a blind resubmit). Staff
            // must use "Check Final Fate" to reconcile before assuming
            // either outcome.
            if (isset($client)) {
                $this->flashCollexiaDebug($client, 'Mandate Load');
            }
            $this->debitOrders->updateCollexiaApiState($id, [
                'collexia_api_status' => 'Uncertain',
                'collexia_api_last_response' => 'Network error, outcome unknown: ' . $e->getMessage(),
                'collexia_api_synced_at' => date('Y-m-d H:i:s'),
            ]);
            Audit::log(
                'Uncertain',
                'Debit Orders',
                'Collexia mandate request outcome unknown after network error for debit order #' . $id . ' (' . $contractReference . ')',
                ['exception' => $e->getMessage()]
            );
            Session::flash('error', "The request may or may not have reached Collexia (network error). Status marked Uncertain -- use \"Check Final Fate\" to confirm before resubmitting.");
        }
    }

    /**
     * Places a mandate for every split transaction still waiting to be sent
     * (status Not Placed or Load Failed, and not folded away by a merge) --
     * NOT necessarily all of them, since placement can now happen
     * incrementally (a merge creates one new split while its siblings stay
     * however they already were). Amounts come from the split rows created
     * at registration (or by a merge), never recomputed here.
     *
     * Snapshots which loan_schedules row each of Collexia's 1..N
     * installment sequence numbers corresponds to (DebitOrderInstallmentTarget)
     * on the FIRST placement only -- re-snapshotting later could remap
     * already-live splits to a different installment than Collexia already
     * knows them by, since the loan's unpaid-schedule state can have moved
     * on by the time a later split (e.g. a merge result) gets placed.
     */
    private function placeSplitMandate(array $debitOrder, int $banId): void
    {
        $id = (int) $debitOrder['id'];
        // See placeSingleMandate() -- clientNo is the staff-recognised loan
        // reference, userReference is minted separately from this debit
        // order's own id. Kept separate here too rather than reusing one
        // value for both spec concepts.
        $clientNoBase = $debitOrder['borrower_loan_ref_no'] ?: $debitOrder['debit_order_no'];

        $pending = array_values(array_filter(
            $this->splitLegs->activeForDebitOrder($id),
            fn ($s) => in_array($s['collexia_api_status'], self::SPLIT_UNSENT_STATUSES, true)
        ));

        if (empty($pending)) {
            Session::flash('error', 'No split transaction is waiting to be placed.');
            return;
        }

        if (!$this->installmentTargets->hasSnapshot($id)) {
            $this->installmentTargets->snapshot($id, $this->debitOrders->orderedUnpaidScheduleIds((int) $debitOrder['loan_id']));
        }

        $anyFailed = false;
        $placedSummary = [];

        foreach ($pending as $split) {
            $result = $this->attemptSplitPlacement($debitOrder, $split, $banId, $clientNoBase);
            if ($result['success']) {
                $placedSummary[] = 'split #' . (int) $split['split_no'] . ' ' . format_money((float) $split['leg_amount']);
            } else {
                $anyFailed = true;
            }
        }

        $this->rollupSplitStatus($id);

        Audit::log('Update', 'Debit Orders', 'Placed split Collexia API mandate(s) for debit order #' . $id . ': ' . implode(', ', $placedSummary));

        if ($anyFailed) {
            Session::flash('error', 'At least one split transaction was rejected. See Split Transactions for details.');
        } else {
            Session::flash('success', count($pending) . ' split transaction(s) submitted. Use "Check Final Fate" to confirm registration.');
        }
    }

    /**
     * Places (or retries) the Collexia mandate for exactly one split leg --
     * shared by the bulk "place every pending split" loop above and
     * placeSingleSplitMandate()'s targeted single-split retry. Always
     * records the attempted contractReference, success or not (see the
     * comment on the Load Failed branch below for why).
     *
     * A brand-new split (status Not Placed) uses the deterministic
     * debitOrderId+splitNo reference (buildContractReference() below) --
     * guaranteed distinct from its sibling splits even when several are
     * placed in the same tight loop (bulk placement), which the
     * time-based format below cannot guarantee (see its own docblock).
     * A RETRY (status already Load Failed) switches to
     * CollexiaClient::buildContractReference() instead -- the format
     * actually confirmed against Collexia's own Postman pre-request
     * script (GID+MMDD+HHmmss), safe here because a retry is one isolated
     * call, never part of a same-second batch -- so a rejection caused by
     * Collexia already holding the OLD deterministic reference (e.g. code
     * 10543 "Duplicate...") gets a genuinely fresh reference to try
     * instead of recomputing the exact same one forever.
     *
     * noOfInstallments is hardcoded to 1 (2026-10-16: was previously the
     * loan's full remaining-installment count, e.g. 2 for a 2-month loan --
     * applied unchanged to EVERY split leg, so Collexia registered each
     * leg as its own recurring monthly mandate and would have collected
     * each leg's amount again the following month, not once as intended.
     * A split here represents dividing ONE installment across parallel
     * legs for a one-time collection; placing next month's installment
     * (split or not) is a separate, later action, not something this
     * mandate should recur into on its own).
     *
     * @return array{success: bool, message: string}
     */
    private function attemptSplitPlacement(array $debitOrder, array $split, int $banId, string $clientNoBase): array
    {
        $id = (int) $debitOrder['id'];
        $splitNo = (int) $split['split_no'];
        $amount = (float) $split['leg_amount'];

        $maxAmount = $this->settings->maxSingleMandateAmount();
        if ($maxAmount !== null && $amount > $maxAmount) {
            // Rejected locally, before ever calling Collexia -- no point
            // spending a live API call on an amount we already have direct
            // evidence Collexia will reject (code 10569, see
            // CollexiaSetting::maxSingleMandateAmount()'s own docblock).
            $message = 'Split #' . $splitNo . ' (' . format_money($amount) . ') exceeds the configured max single mandate amount of '
                . format_money($maxAmount) . ' -- not sent to Collexia. Split this amount into smaller legs instead.';
            $this->splitLegs->updateState($id, $splitNo, [
                'collexia_api_status' => 'Load Failed',
                'collexia_api_last_response' => $message,
                'collexia_api_synced_at' => date('Y-m-d H:i:s'),
            ]);
            return ['success' => false, 'message' => $message];
        }

        $isRetry = $split['collexia_api_status'] === 'Load Failed';
        $contractReference = $isRetry
            ? (new CollexiaClient())->buildContractReference()
            : $this->buildContractReference($id, $splitNo);
        $suffix = self::splitSuffix($splitNo);

        // userReference (spec 9.3) only needs to be unique per
        // concurrently-live mandate -- confirmed: two concurrently-live
        // mandates sharing one userReference get a "Duplicate..."
        // rejection, same as a retry does (see below). It's minted from
        // this debit order's own auto-increment id (never the loan
        // reference -- that now lives in clientNo, shared across every
        // split leg) plus the split suffix, well within the field's
        // 10-character cap and guaranteed distinct per split leg without
        // ever reading as a real loan reference the way a truncated
        // "SDLOAN0005" base once did.
        //
        // A retry rejected as "Duplicate UserReference or Internal
        // Contract Reference" even after the contract reference above was
        // made provably fresh (a real case, not hypothetical -- see debit
        // order #36 split #2) means the userReference itself, not the
        // contract reference, is the actual duplicate at Collexia. The
        // id-based value above is deterministic, so a retry needs its own
        // fresh value the same way -- "R" + SAST HHmmss (6 digits, same
        // correct-timezone source as buildContractReference() above, not
        // the server's UTC clock) + the split suffix.
        $userReference = $isRetry
            ? 'R' . CollexiaClient::sastDateTimeParts()['time'] . $suffix
            : 'DO' . str_pad((string) $id, 7, '0', STR_PAD_LEFT) . $suffix;

        // NOT suffixed (unlike userReference) -- clientNo is the
        // staff-recognised DesertLedger loan reference (e.g. "SDLOAN0003"),
        // so every split leg of the same loan correctly shares one
        // clientNo rather than looking like two different borrowers' loans
        // on Collexia's own portal. Same value as placeSingleMandate()'s
        // non-split path.
        $clientNo = substr((string) $clientNoBase, 0, 15);

        // Found 2026-10-18 on debit order #3 (Helenna Nashinwe, loan
        // LN-261016-7A1D55): this used to always fall back to the debit
        // order's own start_date below, which is only correct for the
        // very first month's splits (where start_date IS the first
        // installment's due date). Every later month added via "Add
        // Splits for Next Installment" carries its own schedule_id
        // already -- use THAT installment's real due_date so Collexia
        // schedules the first (and, since noOfInstallments is always 1,
        // only) collection attempt on the actual amortization date
        // instead of defaulting to "as soon as possible", which is what
        // produced a live mandate collecting two days after placement for
        // an installment not due for another month.
        $scheduleId = $split['schedule_id'] ?? null;
        $firstCollectionDate = $debitOrder['start_date'];
        $collectionDay = CollexiaV3Codes::collectionDay((int) $debitOrder['debit_day']);
        if (!empty($split['collection_date'])) {
            // "One mandate per scheduled installment" legs carry their own
            // exact collection date (the installment's due date, or the
            // earliest valid future date if it's already past due) -- the
            // day-of-month rule follows that same date, not the debit
            // order's single debit_day, since every installment can fall
            // on a different day.
            $firstCollectionDate = $split['collection_date'];
            $collectionDay = CollexiaV3Codes::collectionDay((int) date('j', strtotime((string) $firstCollectionDate)));
        } elseif ($scheduleId) {
            $schedule = $this->loans->scheduleRow((int) $scheduleId);
            if ($schedule) {
                $firstCollectionDate = $schedule['due_date'];
            }
        }

        $mandate = [
            'clientNo' => $clientNo,
            // Unique per split leg -- see this method's docblock above for
            // why it can no longer be the loan reference.
            'userReference' => $userReference,
            'frequencyCode' => 4,
            'installmentAmount' => $amount,
            // Always 1 -- see this method's docblock. A split leg is one
            // one-time collection of its share of a single installment,
            // never a recurring series of its own.
            'noOfInstallments' => 1,
            // Always the Remote GID, never 0 -- confirmed by Collexia.
            'origin' => (int) $this->settings->get('collexia_remote_gid'),
            'contractReference' => $contractReference,
            'magId' => CollexiaV3Codes::MAG_ID_ENDO,
            'initialAmount' => 0,
            'firstCollectionDate' => date('Ymd', strtotime((string) $firstCollectionDate)),
            'collectionDay' => $collectionDay,
            'numberOfTrackingDays' => (int) $debitOrder['no_of_days_tracking'],
            'debtorAccountName' => $debitOrder['account_name'] ?: $debitOrder['borrower_name'],
            'debtorIdentificationType' => 1,
            'debtorIdentificationNo' => $debitOrder['id_number'],
            'debtorAccountNumber' => $debitOrder['account_number'],
            'debtorAccountType' => (int) $debitOrder['account_type'],
            'debtorBanId' => $banId,
        ] + ($this->settings->v4FieldsEnabled() ? self::mandateDebtorExtraFields($debitOrder) : []);

        try {
            $client = new CollexiaEndoApiClient();
            $client->loadMandate($mandate, $this->frontEndUserName());

            $this->splitLegs->updateState($id, $splitNo, [
                'collexia_api_contract_reference' => $contractReference,
                'collexia_client_no' => $clientNo,
                'collexia_user_reference' => $userReference,
                'collexia_api_status' => 'Load Pending',
                'collexia_api_last_response' => 'Mandate submitted. Call "Check Final Fate" to confirm registration.',
                'collexia_api_synced_at' => date('Y-m-d H:i:s'),
            ]);
            return ['success' => true, 'message' => 'Split #' . $splitNo . ' submitted (' . $contractReference . '). Use "Check Final Fate" to confirm registration.'];
        } catch (CollexiaApiException $e) {
            // contractReference is deterministic (debit order id + split
            // no + today's date, see buildContractReference()) -- stored
            // even on failure, not just success, so a rejection caused
            // by Collexia already holding this exact mandate (e.g. code
            // 10543 "Duplicate UserReference or Internal Contract
            // Reference", from an earlier attempt that DesertLedger
            // never got local confirmation of) can still be resolved via
            // Check Final Fate below instead of being stuck forever with
            // no reference to check.
            $this->splitLegs->updateState($id, $splitNo, [
                'collexia_api_contract_reference' => $contractReference,
                'collexia_client_no' => $clientNo,
                'collexia_user_reference' => $userReference,
                'collexia_api_status' => 'Load Failed',
                'collexia_api_last_response' => $e->getMessage(),
                'collexia_api_synced_at' => date('Y-m-d H:i:s'),
            ]);
            return ['success' => false, 'message' => 'Split #' . $splitNo . ' was rejected: ' . $e->getMessage()];
        } catch (\RuntimeException $e) {
            $this->splitLegs->updateState($id, $splitNo, [
                'collexia_api_contract_reference' => $contractReference,
                'collexia_client_no' => $clientNo,
                'collexia_user_reference' => $userReference,
                'collexia_api_status' => 'Load Failed',
                'collexia_api_last_response' => $e->getMessage(),
                'collexia_api_synced_at' => date('Y-m-d H:i:s'),
            ]);
            return ['success' => false, 'message' => 'Split #' . $splitNo . ' failed: ' . $e->getMessage()];
        }
    }

    public function checkFinalFate(string $id): void
    {
        Auth::authorize('collections.debit_orders');
        $debitOrder = $this->loadOr404($id);
        if (!$debitOrder) {
            return;
        }
        if (!$this->verifyCsrfOrRedirect($id)) {
            return;
        }

        if ((int) ($debitOrder['split_enabled'] ?? 0) === 1) {
            $this->checkSplitFinalFate($debitOrder);
            $this->redirect('/debit-orders/' . $id);
            return;
        }

        if (!$debitOrder['collexia_api_contract_reference']) {
            Session::flash('error', 'This mandate has not been placed yet.');
            $this->redirect('/debit-orders/' . $id);
            return;
        }

        try {
            $client = new CollexiaEndoApiClient();
            $result = $client->requestFinalFate((string) $debitOrder['collexia_api_contract_reference'], $this->frontEndUserName());
            $this->flashCollexiaDebug($client, 'Final Fate');

            $loaded = !empty($result['mandateLoaded']);
            // authorizationOutstanding (spec 9.5): 1-Y, 2-N -- a mandate can
            // come back "loaded" but still awaiting the debtor's/bank's own
            // authorization step, so a plain "Registered" would overstate
            // how final this actually is.
            $authOutstanding = $loaded && (int) ($result['authorizationOutstanding'] ?? 2) === 1;
            $this->debitOrders->updateCollexiaApiState((int) $id, [
                'collexia_api_status' => $loaded ? 'Registered' : 'Load Failed',
                'collexia_api_last_response' => json_encode($result),
                'collexia_api_synced_at' => date('Y-m-d H:i:s'),
            ]);

            Audit::log('Update', 'Debit Orders', 'Checked Collexia final fate for debit order #' . $id . ' -> ' . ($loaded ? 'Registered' : 'Load Failed'));
            Session::flash($loaded ? 'success' : 'error', $loaded
                ? ('Mandate confirmed registered.' . ($authOutstanding ? ' Authorization is still outstanding -- Collexia has not yet confirmed the debtor/bank has authorized it.' : ''))
                : 'The mandate did not register (code ' . ($result['mandateLoadedResponseCode'] ?? '?') . ').');
        } catch (\RuntimeException $e) {
            if (isset($client)) {
                $this->flashCollexiaDebug($client, 'Final Fate');
            }
            Session::flash('error', $e->getMessage());
        }

        $this->redirect('/debit-orders/' . $id);
    }

    private function checkSplitFinalFate(array $debitOrder): void
    {
        $id = (int) $debitOrder['id'];
        $splits = $this->splitLegs->activeForDebitOrder($id);
        $attempted = false;
        $allLoaded = true;
        $anyAuthOutstanding = false;

        foreach ($splits as $split) {
            // Also re-checks a Load Failed split, as long as it has a
            // contract reference on file -- a genuine rejection (bad
            // debtor details, etc.) will just be confirmed not-loaded again
            // here (harmless, read-only), but a "Duplicate" rejection
            // (Collexia already holding this exact deterministic reference
            // from an earlier attempt) gets a real chance to resolve to
            // Registered instead of being permanently stuck.
            if (!in_array($split['collexia_api_status'], ['Load Pending', 'Load Failed'], true) || !$split['collexia_api_contract_reference']) {
                continue;
            }
            $attempted = true;

            try {
                $client = new CollexiaEndoApiClient();
                $result = $client->requestFinalFate((string) $split['collexia_api_contract_reference'], $this->frontEndUserName());
                $loaded = !empty($result['mandateLoaded']);
                if ($loaded && (int) ($result['authorizationOutstanding'] ?? 2) === 1) {
                    $anyAuthOutstanding = true;
                }

                $this->splitLegs->updateState($id, (int) $split['split_no'], [
                    'collexia_api_status' => $loaded ? 'Registered' : 'Load Failed',
                    'collexia_api_last_response' => json_encode($result),
                    'collexia_api_synced_at' => date('Y-m-d H:i:s'),
                ]);
                $allLoaded = $allLoaded && $loaded;
            } catch (\RuntimeException $e) {
                Session::flash('error', $e->getMessage());
                return;
            }
        }

        if (!$attempted) {
            Session::flash('error', 'No split transaction is awaiting confirmation.');
            return;
        }

        $this->rollupSplitStatus($id);

        Audit::log('Update', 'Debit Orders', 'Checked Collexia final fate for split debit order #' . $id);
        Session::flash($allLoaded ? 'success' : 'error', $allLoaded
            ? ('All submitted split transactions confirmed registered.' . ($anyAuthOutstanding ? ' At least one still has authorization outstanding -- Collexia has not yet confirmed the debtor/bank has authorized it.' : ''))
            : 'At least one split transaction did not register. See Split Transactions for details.');
    }

